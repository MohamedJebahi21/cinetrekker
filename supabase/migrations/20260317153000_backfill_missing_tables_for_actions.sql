-- -----------------------------
-- collection_items
-- -----------------------------
CREATE TABLE IF NOT EXISTS public.collection_items (
  collection_id BIGINT NOT NULL REFERENCES public.collections(id) ON DELETE CASCADE,
  media_id BIGINT NOT NULL,
  media_type TEXT NOT NULL CHECK (media_type IN ('movie', 'tv')),
  added_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (collection_id, media_id, media_type)
);

CREATE INDEX IF NOT EXISTS idx_collection_items_collection_id
  ON public.collection_items (collection_id);

ALTER TABLE public.collection_items ENABLE ROW LEVEL SECURITY;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public' AND tablename = 'collection_items' AND policyname = 'collection_items_select_own'
  ) THEN
    CREATE POLICY collection_items_select_own
      ON public.collection_items FOR SELECT
      USING (
        EXISTS (
          SELECT 1
          FROM public.collections c
          WHERE c.id = collection_id
            AND c.user_id = auth.uid()
        )
      );
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public' AND tablename = 'collection_items' AND policyname = 'collection_items_insert_own'
  ) THEN
    CREATE POLICY collection_items_insert_own
      ON public.collection_items FOR INSERT
      WITH CHECK (
        EXISTS (
          SELECT 1
          FROM public.collections c
          WHERE c.id = collection_id
            AND c.user_id = auth.uid()
        )
      );
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public' AND tablename = 'collection_items' AND policyname = 'collection_items_delete_own'
  ) THEN
    CREATE POLICY collection_items_delete_own
      ON public.collection_items FOR DELETE
      USING (
        EXISTS (
          SELECT 1
          FROM public.collections c
          WHERE c.id = collection_id
            AND c.user_id = auth.uid()
